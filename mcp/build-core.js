// Builds core/sim-core.js: the page's simulation (seeded random .. sim step) plus carPos,
// with the DOM stripped and a few hooks for the MCP game, followed by core/harness.js.
// Usage: node build-core.js [../index.html]
// Patches match exact strings and fail loudly if the page's sim code changes.
const fs = require('fs');
const path = require('path');
const src = process.argv[2] || path.join(__dirname, '..', 'index.html');
const html = fs.readFileSync(src, 'utf8');
let core = html.split('/* ---------------- seeded random ---------------- */')[1].split('/* ---------------- map drawing ---------------- */')[0];
const rep = (a, b) => { if (!core.includes(a)) throw new Error('patch miss: ' + a.slice(0, 70)); core = core.split(a).join(b); };

// feed and toasts become an event list the server reads
core = core.replace(/const feedEl = \$\('feed'\);\n(function clockStr[^\n]*\n)[\s\S]*?\nlet toastTimer = 0;\nfunction toast\(msg\) \{[^\n]*\n/, (m, clock) =>
  clock + "function log({ src = 'exec', kind = 'system', tag, head, body, alts }) { if (S.shadow) return; EVENTS.push({ t: S.t, src, kind, tag, head, body, alts }); }\nfunction toast() {}\n");
if (core.includes("$('feed')")) throw new Error('patch miss: feed');
rep('car.drawT = performance.now();', 'car.drawT = 0;');
// hazards run for the whole game, not just until 16:00
rep('while (t < 16 * 3600) {', 'while (t < HAZ_END) {');
// game demand: the seed's riders/hr times a game multiplier
rep('const rate = S.rph * (S.rush ? 1.5 : 1)', 'const rate = S.rph * DEMAND * (S.rush ? 1.5 : 1)');
// a model playing over MCP replaces the scripted agent's routines, but keeps the fleet's sensors and traffic-aware routing
rep('if (S.agent) agentDispatchAll(); else', 'if (S.external) return; if (S.agent) agentDispatchAll(); else');
rep('agentCharge(); T.charge = S.t + 10;', 'if (!S.external) agentCharge(); T.charge = S.t + 10;');
rep('agentReroute(); T.reroute = S.t + 25;', 'if (!S.external) agentReroute(); T.reroute = S.t + 25;');
rep('agentReposition(); T.repo = S.t + 180;', 'if (!S.external) agentReposition(); T.repo = S.t + 180;');
rep('  const n = agentReroute();\n  if (!n) log(', '  const n = S.external ? 1 : agentReroute();\n  if (!n) log(');
rep("if (S.agent) log({ src: 'agent', kind: 'charge', tag: 'Charge', head: `${car.id} back in service", "if (S.external) log({ src: 'exec', kind: 'charge', tag: 'Charged', head: `${car.id} back in service at ${Math.round(car.battery)}%` }); else if (S.agent) log({ src: 'agent', kind: 'charge', tag: 'Charge', head: `${car.id} back in service");
// economy: fares on drop-off, tow fees on strand (energy is read from batUsed)
rep('p.trips++; p.rideSum += S.t - r.pickT;', 'p.trips++; payFare(p, r, car); p.rideSum += S.t - r.pickT;');
rep('const p = P(); p.stranded++;', 'const p = P(); p.stranded++; p.tows = (p.tows || 0) + 1;');
rep("r.status = 'cancelled'; P().cancelled++;", "r.status = 'cancelled'; P().cancelled++; P().lostFares = (P().lostFares || 0) + fareOf(r);");
rep("const r = { id: 'R-' + S.nextReq++,", "const r = { km: tripKm(from, to), id: 'R-' + S.nextReq++,");

const carPos = html.match(/function carPos\(c\) \{[\s\S]*?\n\}/)[0];
const harness = fs.readFileSync(path.join(__dirname, 'core', 'harness.js'), 'utf8');
// the city: downtown Toronto road graph from map/build.js (the sim needs only the graph, not the scene)
const graph = fs.readFileSync(path.join(__dirname, '..', 'map', 'toronto.graph.json'), 'utf8');
const out = `// GENERATED by build-core.js from ${path.basename(src)}. Do not edit; edit core/harness.js or the patches.
'use strict';
const document = undefined; const $ = () => null; const location = { hash: '' }; const performance = { now: () => 0 };
const EVENTS = []; let HAZ_END = 16 * 3600, DEMAND = 1;
const ROBRO_MAP = { graph: ${graph.trim()} };
${core}
${carPos}
${harness}`;
fs.writeFileSync(path.join(__dirname, 'core', 'sim-core.js'), out);
console.log('wrote core/sim-core.js', out.length, 'bytes');
